export function searchEntries({ query = '', category = 'all', family = 'all', favorites = null } = {}) {
  const words = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return catalog.filter(e => (category === 'all' || e.category === category) &&
    (family === 'all' || e.family === family) && (!favorites || favorites.has(e.id)) &&
    words.every(word => `${e.title} ${e.label} ${e.summary} ${e.tags.join(' ')}`.toLocaleLowerCase().includes(word)));
}
